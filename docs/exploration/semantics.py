import sys
sys.path.insert(0, "baseline_pkg")
from flashtext import KeywordProcessor

def show(kws, text, **kw):
    kp = KeywordProcessor(case_sensitive=True)
    for k in kws: kp.add_keyword(k)
    print("  kws=%-28s text=%-24r -> %s" % (kws, text, kp.extract_keywords(text, **kw)))

print("=== can a keyword match mid-word (suffix)? ===")
show(["the"], "there")
show(["he"], "the")
show(["at"], "cat")
print("=== prefix of a longer word ===")
show(["cat"], "cats")
show(["cat"], "cat9")
show(["cat"], "cat_9")
print("=== multiword spanning punctuation ===")
show(["new york"], "new, york")
show(["new york"], "new. york")
show(["new york"], "new-york")
print("=== longest wins? ===")
show(["new","new york"], "new york city")
show(["new york","new"], "new york city")
print("=== overlapping ===")
show(["abc","bcd"], "abcd")
show(["ab","abc"], "abcd")
print("=== non-ascii / CJK (non_word_boundaries excludes CJK) ===")
show(["计算机"], "我喜欢计算机科学")
show(["计算机"], "计算机")
print("=== empty & weird ===")
show(["a"], "")
show(["a"], "   ")
print("=== digit/underscore are word chars ===")
show(["cat"], "9cat")
show(["cat"], "_cat")
show(["cat"], " cat")
