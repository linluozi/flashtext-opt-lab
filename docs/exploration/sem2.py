import sys
sys.path.insert(0, "baseline_pkg")
from flashtext import KeywordProcessor

def run(kws, text):
    kp = KeywordProcessor(case_sensitive=True)
    for k in kws: kp.add_keyword(k)
    return kp.extract_keywords(text)

print("=== keywords containing leading/trailing boundary chars ===")
print("  kw=' new'  text='a new b'   ->", run([" new"], "a new b"))
print("  kw='new '  text='a new b'   ->", run(["new "], "a new b"))
print("  kw='new york' text='new york'->", run(["new york"], "new york"))
print("  kw='new-york' text='new-york'->", run(["new-york"], "new-york"))
print()
print("=== fallback to shorter when longer fails at boundary ===")
print("  kw=[new, new york] text='new yorker' ->", run(["new","new york"], "new yorker"))
print("  kw=[new, new york] text='new york'   ->", run(["new","new york"], "new york"))
print()
print("=== match must end at boundary ===")
print("  kw=the text='the.'  ->", run(["the"], "the."))
print("  kw=the text='thex'  ->", run(["the"], "thex"))
print("  kw='new york' text='new york.' ->", run(["new york"], "new york."))
print("  kw='new york' text='new yorkx' ->", run(["new york"], "new yorkx"))
print()
print("=== EOS (no trailing boundary) ===")
print("  kw=the text='the'   ->", run(["the"], "the"))
print("  kw='new york' text='new york' ->", run(["new york"], "new york"))
print()
print("=== spans ===")
kp=KeywordProcessor(case_sensitive=True); kp.add_keyword("the")
print("  'the cat' span:", kp.extract_keywords("the cat", span_info=True))
print("  'the'     span:", kp.extract_keywords("the", span_info=True))
print("  'a the b' span:", kp.extract_keywords("a the b", span_info=True))
